"""Strict input preparation and ordered Parquet export for the new B3 experiments.

Only ``prepare_dataset`` may create/update inputs, before job submission. Workers
consume the frozen CSV. TFB timestamps are synthetic daily labels: calendar gaps
are never filled and the sidecar preserves the original trading labels.

Result archives must be locally generated by this checkout: TFB serializes its
predictions with pickle, which is not a safe format for untrusted input.
"""
from __future__ import annotations

import base64
import hashlib
import io
import json
import os
import pickle
import tarfile
import tempfile
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd


SCHEMA_VERSION = 1
STEP_OFFSET = 2
RESERVED_TARGETS = {"date", "step", "origin_step", "h", "arquivo", "cols", "data"}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _date_index(values: pd.Series) -> pd.Index:
    if values.isna().any():
        raise ValueError("The input contains missing trading labels.")
    numeric = pd.to_numeric(values, errors="coerce")
    if numeric.notna().all():
        if not np.isfinite(numeric.to_numpy(dtype=float)).all():
            raise ValueError("Trading step labels must be finite.")
        if not np.equal(numeric, np.floor(numeric)).all():
            raise ValueError("Numeric trading labels must be integer steps.")
        return pd.Index(numeric.astype("int64"), name="date")
    if numeric.notna().any():
        raise ValueError("Do not mix integer trading steps and calendar dates.")
    try:
        dates = pd.to_datetime(values, errors="raise")
    except (TypeError, ValueError) as exc:
        raise ValueError("Invalid input calendar dates.") from exc
    return pd.DatetimeIndex(dates, name="date")


def load_panel(path: Path) -> pd.DataFrame:
    """Read balanced long or wide TFB data, preserving the asset order.

    Missing/duplicate/nonfinite values are rejected, never imputed. Integer
    trading labels stay integers; date strings become timestamps. Positivity is
    checked by ``prepare_dataset`` because this reader also reads log returns.
    """
    path = Path(path)
    # pandas normally mangles duplicate CSV headers; detect them before reading.
    import csv

    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        header = next(csv.reader(stream), [])
    if len(header) != len(set(header)):
        raise ValueError(f"Duplicate CSV columns in {path}.")
    raw = pd.read_csv(path)
    if "date" not in raw or raw.empty:
        raise ValueError(f"Expected a nonempty CSV with a date column: {path}")
    raw["date"] = _date_index(raw["date"])
    if {"cols", "data"}.issubset(raw.columns):
        if set(raw.columns) != {"date", "data", "cols"}:
            raise ValueError("Long price/return data must contain only date,data,cols.")
        if raw["cols"].isna().any():
            raise ValueError("Missing asset identifiers.")
        raw["cols"] = raw["cols"].astype(str)
        targets = raw["cols"].drop_duplicates().tolist()
        if raw.duplicated(["date", "cols"]).any():
            raise ValueError("Duplicate (date, asset) observations.")
        panel = raw.pivot(index="date", columns="cols", values="data")
        panel = panel.reindex(columns=targets)
    else:
        if "cols" in raw or "data" in raw:
            raise ValueError("Malformed long-format input: date,data,cols are required.")
        if raw["date"].duplicated().any():
            raise ValueError("Duplicate trading labels.")
        panel = raw.set_index("date")
    if not len(panel.columns):
        raise ValueError("No assets in the panel.")
    if any(not str(x).strip() or str(x) != str(x).strip() for x in panel.columns):
        raise ValueError("Asset identifiers must be nonempty without outer whitespace.")
    if RESERVED_TARGETS.intersection(panel.columns):
        raise ValueError("Asset identifiers collide with reserved output columns.")
    try:
        panel = panel.apply(pd.to_numeric, errors="raise").astype("float64")
    except (TypeError, ValueError) as exc:
        raise ValueError("All asset observations must be numeric.") from exc
    if not np.isfinite(panel.to_numpy()).all():
        raise ValueError("The panel must be balanced and contain only finite observations; no filling is allowed.")
    panel = panel.sort_index()
    panel.columns.name = None
    panel.index.name = "date"
    return panel


def _atomic_write(path: Path, write: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    os.close(descriptor)
    tmp = Path(name)
    try:
        write(tmp)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def prepare_dataset(source: Path, destination: Path, *, replace: bool = False) -> dict:
    """Freeze log returns from positive prices, with hashes and calendar mapping.

    Existing matching files are reused unchanged. A managed set can only be
    replaced explicitly; an untracked destination is never overwritten. The
    caller must hold its submission/preparation lock and register FORECAST_META.
    """
    source, destination = Path(source).resolve(), Path(destination).resolve()
    if source == destination:
        raise ValueError("The price source and generated-return destination must differ.")
    metadata_path = destination.with_suffix(".metadata.json")
    # TFB scans top-level *.csv files as forecasting datasets. Keep this audit
    # CSV out of that scan: it is a calendar mapping, not a date,data,cols panel.
    calendar_path = destination.parent / ".b3_new" / f"{destination.stem}.calendar.csv"
    source_hash = sha256_file(source)
    existing = None
    if metadata_path.exists():
        existing = json.loads(metadata_path.read_text(encoding="utf-8"))
        if existing.get("schema_version") != SCHEMA_VERSION:
            raise ValueError("Unsupported generated dataset metadata version.")
        if existing.get("source") != str(source) or existing.get("dataset") != str(destination):
            raise ValueError("Generated dataset metadata belongs to another source/destination.")
        valid = (
            existing.get("source_sha256") == source_hash
            and destination.is_file()
            and calendar_path.is_file()
            and sha256_file(destination) == existing.get("dataset_sha256")
            and sha256_file(calendar_path) == existing.get("calendar_sha256")
        )
        if valid:
            return existing
        if not replace:
            raise FileExistsError("Prepared inputs changed or are incomplete; explicitly replace them before submission.")
    elif destination.exists() or calendar_path.exists():
        raise FileExistsError("Refusing to overwrite generated files without ownership metadata.")

    prices = load_panel(source)
    if len(prices) < 3:
        raise ValueError("At least three price observations are required.")
    if not (prices.to_numpy() > 0).all():
        raise ValueError("Log returns require strictly positive prices.")
    # diff(log(price)) avoids an overflowing intermediate price ratio.
    returns = np.diff(np.log(prices.to_numpy()), axis=0)
    dates = pd.date_range("2000-01-02", periods=len(returns), freq="D")
    targets = prices.columns.tolist()
    output = pd.DataFrame({
        "date": np.tile(dates.strftime("%Y-%m-%d"), len(targets)),
        "data": returns.T.reshape(-1),
        "cols": np.repeat(targets, len(returns)),
    })
    calendar = pd.DataFrame({
        "date": dates.strftime("%Y-%m-%d"),
        "return_row": np.arange(len(returns)),
        "origin_step": np.arange(1, len(prices)),
        "step": np.arange(2, len(prices) + 1),
        "source_origin": prices.index[:-1],
        "source_target": prices.index[1:],
    })
    # Detect a concurrent upstream rewrite before publishing the frozen input.
    if sha256_file(source) != source_hash:
        raise RuntimeError("The price source changed during preparation; retry after its writer finishes.")
    _atomic_write(destination, lambda path: output.to_csv(path, index=False))
    _atomic_write(calendar_path, lambda path: calendar.to_csv(path, index=False))
    metadata = {
        "schema_version": SCHEMA_VERSION,
        "source": str(source),
        "dataset": str(destination),
        "source_sha256": source_hash,
        "dataset_sha256": sha256_file(destination),
        "n_prices": len(prices),
        "n_rows": len(returns),
        "n_assets": len(targets),
        "targets": targets,
        "step_offset": STEP_OFFSET,
        "calendar": str(calendar_path),
        "calendar_sha256": sha256_file(calendar_path),
        "metadata": str(metadata_path),
    }
    _atomic_write(metadata_path, lambda path: path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8"))
    return metadata


def _read_payload(result_dir: Path) -> tuple[Any, Any]:
    payloads = []
    archives = sorted(Path(result_dir).glob("*.csv.tar.gz"))
    if not archives:
        raise FileNotFoundError(f"No TFB result archives in {result_dir}.")
    for archive in archives:
        with tarfile.open(archive, "r:gz") as tar:
            for member in tar.getmembers():
                if not member.isfile() or not member.name.endswith(".csv"):
                    continue
                stream = tar.extractfile(member)
                if stream is None:
                    continue
                table = pd.read_csv(io.BytesIO(stream.read()))
                if not {"actual_data", "inference_data"}.issubset(table.columns):
                    continue
                for _, row in table.iterrows():
                    values = [row["actual_data"], row["inference_data"]]
                    if not all(isinstance(value, str) and value.strip() for value in values):
                        raise ValueError("TFB result lacks encoded actual/predicted data; check the benchmark error log.")
                    payloads.append(tuple(pickle.loads(base64.b64decode(value, validate=True)) for value in values))
    if len(payloads) != 1:
        raise ValueError(f"Expected exactly one result payload per task; found {len(payloads)}.")
    return payloads[0]


def _windows_array(payload: Any, panel: pd.DataFrame, cut: int, horizon: int, label: str) -> np.ndarray:
    windows = len(panel) - cut - horizon + 1
    expected_shape = (windows, horizon, len(panel.columns))
    if isinstance(payload, pd.DataFrame):
        payload = [payload]
    if isinstance(payload, (list, tuple)):
        frames = []
        for sample, window in enumerate(payload):
            if isinstance(window, pd.DataFrame):
                expected_index = panel.index[cut + sample : cut + sample + horizon]
                if list(window.columns) != list(panel.columns):
                    raise ValueError(f"{label}: asset columns differ in window {sample}.")
                if not window.index.equals(expected_index):
                    raise ValueError(f"{label}: dates differ in window {sample}.")
                window = window.to_numpy()
            frames.append(np.asarray(window))
        try:
            array = np.stack(frames)
        except ValueError as exc:
            raise ValueError(f"{label}: inconsistent forecast window shapes.") from exc
    else:
        array = np.asarray(payload)
    if array.shape != expected_shape:
        raise ValueError(f"{label}: expected {expected_shape}, received {array.shape}.")
    if not np.issubdtype(array.dtype, np.number) or not np.isfinite(array).all():
        raise ValueError(f"{label}: nonnumeric/nonfinite output.")
    return array


def export_predictions(
    result_dir: Path,
    panel: pd.DataFrame,
    cut: int,
    horizon: int,
    output_dir: Path,
    keep_csv: bool = False,
) -> dict:
    """Validate stride-one rolling predictions and atomically write one Parquet.

    Encoded sequence order is preserved directly, avoiding the historical
    lexicographic sample_1/sample_10/sample_2 sorting bug. Actual targets must
    match the frozen input (float32 roundoff is allowed).
    """
    if cut <= 0 or horizon <= 0 or cut + horizon > len(panel):
        raise ValueError("Invalid test cutoff/horizon for the supplied panel.")
    if not panel.index.is_unique or not panel.index.is_monotonic_increasing:
        raise ValueError("The supplied panel must have a unique chronological index.")
    if not np.isfinite(panel.to_numpy()).all():
        raise ValueError("The supplied panel contains missing/nonfinite observations.")
    actual, prediction = _read_payload(Path(result_dir))
    actual = _windows_array(actual, panel, cut, horizon, "actual_data")
    prediction = _windows_array(prediction, panel, cut, horizon, "inference_data")
    count = len(prediction)
    values = panel.to_numpy()
    for sample in range(count):
        truth = values[cut + sample : cut + sample + horizon]
        if not np.allclose(actual[sample], truth, rtol=1e-7, atol=1e-12):
            raise ValueError(f"Actual targets differ from the supplied dataset in window {sample}; possible ordering/cutoff mismatch.")

    frame = pd.DataFrame(prediction.reshape(count * horizon, -1), columns=panel.columns)
    window_names = [f"janela_{sample:06d}.csv" for sample in range(count)]
    frame.insert(0, "arquivo", np.repeat(window_names, horizon))
    frame["h"] = np.tile(np.arange(1, horizon + 1), count)
    frame["origin_step"] = np.repeat(np.arange(cut + 1, cut + count + 1), horizon)
    frame["step"] = frame["origin_step"] + frame["h"]
    output_dir = Path(output_dir)
    parquet = output_dir / "part.parquet"
    _atomic_write(parquet, lambda path: frame.to_parquet(path, index=False, engine="pyarrow", compression="snappy"))
    if keep_csv:
        for sample, name in enumerate(window_names):
            window = frame.iloc[sample * horizon : (sample + 1) * horizon].drop(columns="arquivo")
            _atomic_write(output_dir / name, lambda path, window=window: window.to_csv(path, index=False))
    return {
        "parquet": str(parquet.resolve()),
        "parquet_sha256": sha256_file(parquet),
        "n_windows": count,
        "n_rows": len(frame),
        "n_assets": len(panel.columns),
        "first_origin_step": cut + 1,
        "last_origin_step": cut + count,
        "first_target_step": cut + 2,
    }
